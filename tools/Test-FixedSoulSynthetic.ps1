<#
.SYNOPSIS
    Modified build: synthetic test of the fixed female figure soul. No game, relay or agent needed.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-FixedSoulSynthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-FixedSoulSynthetic.lua') `
    -Title 'Fixed figure soul synthetic test'
exit $LASTEXITCODE
